//! Little-endian wire primitives and the macros that define POD types.
//!
//! Every POD type of the protocol is `repr(C)`, built from fixed-width
//! integers, `f32`, arrays of those, handles and other POD types, with explicit
//! `_pad` fields instead of implicit padding. `wire_struct!` checks at compile
//! time that `size_of` equals the sum of the field sizes, so the in-memory
//! layout (which the sync-call blocks cross the `Link` in) and the byte layout
//! of the stream are one and the same on the little-endian targets proto
//! supports.

use crate::status::Error;
use alloc::vec::Vec;

#[cfg(not(target_endian = "little"))]
compile_error!("proto assumes a little-endian target (x86_64 PE, x86_64 and arm64 Mach-O)");

/// A fixed-size POD value with a byte form.
pub trait Wire: Sized + Copy {
    /// Bytes on the wire (= `size_of::<Self>()`).
    const SIZE: usize;
    /// All bytes zero.
    const ZERO: Self;
    fn put(&self, out: &mut Vec<u8>);
    fn get(r: &mut Reader<'_>) -> Result<Self, Error>;
}

/// One field of a POD struct: what the generated API table is made of.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FieldInfo {
    pub name: &'static str,
    pub ty: &'static str,
    pub offset: usize,
    pub size: usize,
}

/// Layout description of a POD struct, generated by `wire_struct!`.
pub trait Layout: Wire {
    const NAME: &'static str;
    const FIELDS: &'static [FieldInfo];
}

/// Bounds-checked cursor over a byte slice. Every read is fallible.
#[derive(Clone, Debug)]
pub struct Reader<'a> {
    buf: &'a [u8],
    pos: usize,
}

impl<'a> Reader<'a> {
    pub const fn new(buf: &'a [u8]) -> Self {
        Reader { buf, pos: 0 }
    }

    pub const fn pos(&self) -> usize {
        self.pos
    }

    pub const fn remaining(&self) -> usize {
        self.buf.len() - self.pos
    }

    pub fn take(&mut self, n: usize) -> Result<&'a [u8], Error> {
        if n > self.remaining() {
            return Err(Error::Truncated);
        }
        let out = &self.buf[self.pos..self.pos + n];
        self.pos += n;
        Ok(out)
    }

    pub fn read<T: Wire>(&mut self) -> Result<T, Error> {
        T::get(self)
    }
}

/// `n` rounded up to a multiple of 8 (every payload and block is one).
pub const fn align8(n: usize) -> usize {
    (n + 7) & !7
}

pub(crate) fn pad_to_8(out: &mut Vec<u8>) {
    while !out.len().is_multiple_of(8) {
        out.push(0);
    }
}

macro_rules! int_wire {
    ($($t:ty),*) => {$(
        impl Wire for $t {
            const SIZE: usize = core::mem::size_of::<$t>();
            const ZERO: Self = 0;
            fn put(&self, out: &mut Vec<u8>) {
                out.extend_from_slice(&self.to_le_bytes());
            }
            fn get(r: &mut Reader<'_>) -> Result<Self, Error> {
                let b = r.take(Self::SIZE)?;
                let a = b.try_into().map_err(|_| Error::Truncated)?;
                Ok(<$t>::from_le_bytes(a))
            }
        }
    )*};
}
int_wire!(u8, u16, u32, u64, i32);

impl Wire for f32 {
    const SIZE: usize = 4;
    const ZERO: Self = 0.0;
    fn put(&self, out: &mut Vec<u8>) {
        out.extend_from_slice(&self.to_bits().to_le_bytes());
    }
    fn get(r: &mut Reader<'_>) -> Result<Self, Error> {
        Ok(f32::from_bits(u32::get(r)?))
    }
}

macro_rules! array_wire {
    ($($t:ty),*) => {$(
        impl<const N: usize> $crate::wire::Wire for [$t; N] {
            const SIZE: usize = N * <$t as $crate::wire::Wire>::SIZE;
            const ZERO: Self = [<$t as $crate::wire::Wire>::ZERO; N];
            fn put(&self, out: &mut alloc::vec::Vec<u8>) {
                for v in self {
                    $crate::wire::Wire::put(v, out);
                }
            }
            fn get(r: &mut $crate::wire::Reader<'_>) -> Result<Self, $crate::status::Error> {
                let mut a = [<$t as $crate::wire::Wire>::ZERO; N];
                for v in a.iter_mut() {
                    *v = <$t as $crate::wire::Wire>::get(r)?;
                }
                Ok(a)
            }
        }
    )*};
}
array_wire!(u8, u32, f32);
pub(crate) use array_wire;

/// Defines a `repr(C)` POD struct with all fields public, and its `Wire` and
/// `Layout` impls. `Default` is all-zero.
macro_rules! wire_struct {
    (
        $(#[$m:meta])*
        $vis:vis struct $name:ident {
            $( $(#[$fm:meta])* $f:ident : $t:ty ),* $(,)?
        }
    ) => {
        $(#[$m])*
        #[repr(C)]
        #[derive(Clone, Copy, Debug, PartialEq)]
        $vis struct $name {
            $( $(#[$fm])* pub $f: $t, )*
        }

        impl $crate::wire::Wire for $name {
            const SIZE: usize = 0 $( + <$t as $crate::wire::Wire>::SIZE )*;
            const ZERO: Self = Self { $( $f: <$t as $crate::wire::Wire>::ZERO, )* };
            fn put(&self, out: &mut alloc::vec::Vec<u8>) {
                $( $crate::wire::Wire::put(&self.$f, out); )*
            }
            fn get(r: &mut $crate::wire::Reader<'_>) -> Result<Self, $crate::status::Error> {
                Ok(Self { $( $f: <$t as $crate::wire::Wire>::get(r)?, )* })
            }
        }

        impl $crate::wire::Layout for $name {
            const NAME: &'static str = stringify!($name);
            const FIELDS: &'static [$crate::wire::FieldInfo] = &[
                $( $crate::wire::FieldInfo {
                    name: stringify!($f),
                    ty: stringify!($t),
                    offset: core::mem::offset_of!($name, $f),
                    size: <$t as $crate::wire::Wire>::SIZE,
                }, )*
            ];
        }

        impl Default for $name {
            fn default() -> Self {
                <Self as $crate::wire::Wire>::ZERO
            }
        }

        const _: () = assert!(
            core::mem::size_of::<$name>() == <$name as $crate::wire::Wire>::SIZE,
            "implicit padding: add explicit _pad fields"
        );
    };
}
pub(crate) use wire_struct;

/// A transparent integer newtype whose every bit pattern is valid, with
/// named constants for the values this version of proto defines ("open enum":
/// unknown numbers can be carried and refused, never UB).
macro_rules! open_enum {
    (
        $(#[$m:meta])*
        $vis:vis struct $name:ident($t:ty) {
            $( $(#[$cm:meta])* $c:ident = $v:literal, )*
        }
    ) => {
        $(#[$m])*
        #[repr(transparent)]
        #[derive(Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Default)]
        $vis struct $name(pub $t);

        impl $name {
            $( $(#[$cm])* pub const $c: Self = Self($v); )*

            /// Every `(name, value)` this version of proto defines.
            pub const KNOWN: &'static [(&'static str, $t)] = &[ $( (stringify!($c), $v), )* ];

            pub const fn name(self) -> Option<&'static str> {
                match self.0 {
                    $( $v => Some(stringify!($c)), )*
                    _ => None,
                }
            }

            pub const fn is_known(self) -> bool {
                self.name().is_some()
            }
        }

        impl core::fmt::Debug for $name {
            fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
                match self.name() {
                    Some(n) => write!(f, "{}::{}", stringify!($name), n),
                    None => write!(f, "{}({:#x})", stringify!($name), self.0),
                }
            }
        }

        impl $crate::wire::Wire for $name {
            const SIZE: usize = core::mem::size_of::<$t>();
            const ZERO: Self = Self(0);
            fn put(&self, out: &mut alloc::vec::Vec<u8>) {
                $crate::wire::Wire::put(&self.0, out);
            }
            fn get(r: &mut $crate::wire::Reader<'_>) -> Result<Self, $crate::status::Error> {
                Ok(Self(<$t as $crate::wire::Wire>::get(r)?))
            }
        }
    };
}
pub(crate) use open_enum;
